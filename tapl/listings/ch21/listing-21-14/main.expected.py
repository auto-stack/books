# Python
import math

x = 2.0
y = 3.0

power = x ** y
sqrt_val = math.sqrt(x)
print(f"{x} ^ {y} = {power}")
print(f"sqrt({x}) = {sqrt_val}")

neg = -5.0
abs_result = abs(neg)
print(f"|{neg}| = {abs_result}")

pi = math.pi
sin_val = math.sin(pi)
cos_val = math.cos(pi)
print(f"sin(pi) = {sin_val}")
print(f"cos(pi) = {cos_val}")
